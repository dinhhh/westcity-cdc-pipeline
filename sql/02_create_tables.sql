-- Branch (BSB = 6-digit branch code)
CREATE TABLE branch (
    branch_id    integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bsb          char(6)      NOT NULL UNIQUE CHECK (bsb ~ '^[0-9]{6}$'),
    branch_name  varchar(100) NOT NULL,
    state        varchar(3)   NOT NULL CHECK (state IN ('NSW','VIC','QLD','SA','WA','TAS','NT','ACT'))
);

-- Products
CREATE TABLE product (
    product_code  varchar(20)  PRIMARY KEY,                          -- e.g. EVERYDAY
    product_name  varchar(100) NOT NULL,
    product_type  varchar(20)  NOT NULL CHECK (product_type IN ('TRANSACTION','SAVINGS')),
    monthly_fee   numeric(8,2) NOT NULL DEFAULT 0 CHECK (monthly_fee >= 0),      -- AUD per month
    interest_rate numeric(5,2) NOT NULL DEFAULT 0 CHECK (interest_rate >= 0),    -- % per year, e.g. 4.50
    is_active     boolean      NOT NULL DEFAULT true
);

-- Customers
CREATE TABLE customer (
    customer_id        bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name         varchar(100) NOT NULL,
    last_name          varchar(100) NOT NULL,
    date_of_birth      date         NOT NULL,
    email              varchar(255) NOT NULL,
    mobile             varchar(16)  NOT NULL CHECK (mobile ~ '^\+[1-9][0-9]{7,14}$'),  -- E.164
    marketing_consent  boolean      NOT NULL DEFAULT false,
    statement_delivery varchar(5)   NOT NULL DEFAULT 'EMAIL' CHECK (statement_delivery IN ('PAPER','EMAIL')),
    customer_since     date         NOT NULL DEFAULT current_date,
    version            integer      NOT NULL DEFAULT 1 CHECK (version >= 1),  -- +1 on every change
    created_at         timestamptz  NOT NULL DEFAULT now(),
    updated_at         timestamptz  NOT NULL DEFAULT now()
);

-- Address history (valid_to NULL = current)
CREATE TABLE customer_address (
    address_id   bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  bigint       NOT NULL REFERENCES customer (customer_id),
    address_type varchar(11)  NOT NULL CHECK (address_type IN ('RESIDENTIAL','POSTAL')),
    line1        varchar(200) NOT NULL,
    suburb       varchar(100) NOT NULL,
    state        varchar(3)   NOT NULL CHECK (state IN ('NSW','VIC','QLD','SA','WA','TAS','NT','ACT')),
    postcode     char(4)      NOT NULL CHECK (postcode ~ '^[0-9]{4}$'),
    valid_from   date         NOT NULL DEFAULT current_date,
    valid_to     date,                                               -- NULL = current address
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);
-- One current address per type
CREATE UNIQUE INDEX ux_customer_address_current
    ON customer_address (customer_id, address_type) WHERE valid_to IS NULL;

-- Account: PENDING until the fraud decision
CREATE TABLE account (
    account_id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id             integer     NOT NULL REFERENCES branch (branch_id),
    account_number        varchar(9)  NOT NULL CHECK (account_number ~ '^[0-9]{6,9}$'),
    product_code          varchar(20) NOT NULL REFERENCES product (product_code),
    account_status        varchar(8)  NOT NULL DEFAULT 'PENDING'
                          CHECK (account_status IN ('PENDING','ACTIVE','REJECTED','CLOSED')),
    channel               varchar(6)  NOT NULL CHECK (channel IN ('MOBILE','BRANCH','WEB')),
    opened_at             timestamptz NOT NULL DEFAULT now(),
    activated_at          timestamptz CHECK (activated_at >= opened_at),
    closed_at             timestamptz CHECK (closed_at >= opened_at),
    onboarding_session_id uuid,                                      -- logical key -> identity_fraud.onboarding_session
    version               integer     NOT NULL DEFAULT 1 CHECK (version >= 1),  -- aggregate version
    updated_at            timestamptz NOT NULL DEFAULT now(),        -- set by trigger in 03
    UNIQUE (branch_id, account_number)                               -- unique per branch
);

-- Account holders (many-to-many)
CREATE TABLE account_holder (
    account_id  bigint      NOT NULL REFERENCES account (account_id),
    customer_id bigint      NOT NULL REFERENCES customer (customer_id),
    holder_role varchar(7)  NOT NULL CHECK (holder_role IN ('PRIMARY','JOINT')),
    added_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (account_id, customer_id)
);
-- One PRIMARY holder per account
CREATE UNIQUE INDEX ux_account_holder_primary
    ON account_holder (account_id) WHERE holder_role = 'PRIMARY';
CREATE INDEX ix_account_holder_customer ON account_holder (customer_id);

-- Transactional outbox, read by Debezium
CREATE TABLE outbox (
    id            uuid         PRIMARY KEY DEFAULT gen_random_uuid(),  -- event id
    aggregatetype varchar(255) NOT NULL CHECK (aggregatetype IN ('account','customer')),  -- Kafka topic
    aggregateid   varchar(255) NOT NULL,                              -- Kafka key
    type          varchar(255) NOT NULL CHECK (type IN ('CustomerCreated','CustomerDetailsUpdated',
                                                        'AccountOpened','AccountActivated',
                                                        'AccountRejected','AccountSnapshot')),
    event_version integer      NOT NULL,                              -- aggregate version after the change
    payload       jsonb        NOT NULL,                              -- full event
    tx_id         bigint       NOT NULL DEFAULT txid_current(),       -- for lineage
    created_at    timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_outbox_created_at ON outbox (created_at);


-- 2. identity_fraud
\connect identity_fraud

-- Device (hashed fingerprint)
CREATE TABLE device (
    device_id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_fingerprint varchar(64) NOT NULL UNIQUE                   -- hashed
);

-- Onboarding session
CREATE TABLE onboarding_session (
    session_id  uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id bigint      NOT NULL,                                -- logical key -> core_banking.customer
    device_id   bigint      NOT NULL REFERENCES device (device_id),
    started_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_onboarding_session_device ON onboarding_session (device_id);  -- shared-device lookup

-- KYC checks (latest attempt counts)
CREATE TABLE kyc_verification (
    kyc_id      bigint     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint     NOT NULL,                                 -- logical key -> core_banking.customer
    attempt_no  integer    NOT NULL DEFAULT 1 CHECK (attempt_no >= 1),
    result      varchar(5) NOT NULL CHECK (result IN ('PASS','FAIL','REFER')),
    UNIQUE (customer_id, attempt_no)
);

-- Watchlist screening
CREATE TABLE watchlist_screening (
    screening_id bigint     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  bigint     NOT NULL UNIQUE,                         -- logical key -> core_banking.customer
    match_status varchar(9) NOT NULL CHECK (match_status IN ('CLEAR','POSSIBLE','CONFIRMED'))
);

-- Risk assessment, one per account
CREATE TABLE risk_assessment (
    assessment_id bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    bigint      NOT NULL UNIQUE,                       -- logical key -> core_banking.account
    customer_id   bigint      NOT NULL,                              -- logical key -> core_banking.customer
    risk_score    integer     NOT NULL CHECK (risk_score BETWEEN 0 AND 100),
    risk_band     varchar(6)  NOT NULL CHECK (risk_band IN ('LOW','MEDIUM','HIGH')),
    decision      varchar(7)  NOT NULL CHECK (decision IN ('APPROVE','REVIEW','DECLINE')),
    reason_codes  text,                                              -- e.g. 'SHARED_DEVICE,KYC_FAIL' (NULL = no signals)
    assessed_at   timestamptz NOT NULL DEFAULT now()                 -- decision time
);

-- Processed Kafka events (idempotency)
CREATE TABLE processed_event (
    event_id     uuid        PRIMARY KEY,
    processed_at timestamptz NOT NULL DEFAULT now()
);

-- 3. crm

\connect crm

-- CRM contact (segment by age at opening)
CREATE TABLE crm_contact (
    contact_id     bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    bigint      NOT NULL UNIQUE,                      -- golden key from core_banking
    segment        varchar(18) NOT NULL
                   CHECK (segment IN ('STUDENT','YOUNG_PROFESSIONAL','FAMILY','SENIOR')),
    source_version integer     NOT NULL,                             -- core customer.version last applied
    synced_at      timestamptz NOT NULL DEFAULT now()
);

-- CRM account; lifecycle_stage follows the account version
CREATE TABLE crm_financial_account (
    fin_account_id  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      bigint      NOT NULL UNIQUE,                     -- golden key from core_banking
    contact_id      bigint      NOT NULL REFERENCES crm_contact (contact_id),
    account_status  varchar(8)  NOT NULL
                    CHECK (account_status IN ('PENDING','ACTIVE','REJECTED','CLOSED')),
    lifecycle_stage varchar(14) NOT NULL
                    CHECK (lifecycle_stage IN ('UNDER_REVIEW','NEW_ONBOARDING','ESTABLISHED','DECLINED')),
    source_version  integer     NOT NULL,                            -- core account.version last applied
    synced_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_crm_financial_account_contact ON crm_financial_account (contact_id);

-- CRM cases (one welcome call per ACTIVE account)
CREATE TABLE crm_case (
    case_id     bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  bigint      NOT NULL REFERENCES crm_financial_account (account_id),
    case_type   varchar(12) NOT NULL DEFAULT 'WELCOME_CALL' CHECK (case_type IN ('WELCOME_CALL')),
    case_status varchar(9)  NOT NULL DEFAULT 'OPEN' CHECK (case_status IN ('OPEN','COMPLETED')),
    opened_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (account_id, case_type)                                   -- at most one welcome call per account
);

-- Processed Kafka events (idempotency)
CREATE TABLE processed_event (
    event_id     uuid        PRIMARY KEY,
    processed_at timestamptz NOT NULL DEFAULT now()
);


