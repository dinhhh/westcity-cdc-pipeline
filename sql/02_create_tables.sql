-- 5a. ops (created first, other layers store run_id)

-- ETL runs
CREATE TABLE ops.etl_run (
    run_id         bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_name       varchar(100) NOT NULL,                            -- e.g. '01_extract_bronze'
    script_version varchar(40)  NOT NULL,                            -- e.g. 'v1'
    started_at     timestamptz  NOT NULL DEFAULT now(),
    finished_at    timestamptz,
    status         varchar(9)   NOT NULL DEFAULT 'RUNNING' CHECK (status IN ('RUNNING','SUCCEEDED','FAILED')),
    rows_read      integer      NOT NULL DEFAULT 0,
    rows_loaded    integer      NOT NULL DEFAULT 0,
    rows_rejected  integer      NOT NULL DEFAULT 0
);

-- Rows that failed data-quality checks
CREATE TABLE ops.dq_quarantine (
    quarantine_id  bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         bigint       NOT NULL REFERENCES ops.etl_run (run_id),
    source_table   varchar(100) NOT NULL,
    record_key     varchar(100) NOT NULL,
    rule_name      varchar(100) NOT NULL,
    reason         text         NOT NULL,
    raw_record     jsonb,                                            -- rejected row
    quarantined_at timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (source_table, record_key, rule_name)                     -- one report per problem
);

-- Incremental extract watermarks
CREATE TABLE ops.extract_watermark (
    source_table     varchar(60) PRIMARY KEY,                        -- e.g. 'crm.crm_case'
    watermark_column varchar(30) NOT NULL,                           -- the source column compared
    last_id          bigint,                                         -- highest id copied so far
    last_ts          timestamptz,                                    -- latest synced_at copied so far
    run_id           bigint,                                         -- run that last moved it
    updated_at       timestamptz NOT NULL DEFAULT now()
);

-- 5b. bronze: raw data, no constraints besides keys

-- Core banking events from Kafka
CREATE TABLE bronze.core_event (
    event_id          uuid         PRIMARY KEY,                      -- = outbox id
    event_type        varchar(40)  NOT NULL,                         -- e.g. AccountOpened
    aggregate_type    varchar(20)  NOT NULL,                         -- 'customer' or 'account'
    aggregate_id      bigint       NOT NULL,                         -- customer_id or account_id
    aggregate_version integer      NOT NULL,                         -- version after the change
    occurred_at       timestamptz  NOT NULL,                         -- commit time in core_banking
    payload           jsonb        NOT NULL,                         -- the whole event, unchanged
    kafka_topic       varchar(100) NOT NULL,                         -- Kafka topic
    kafka_partition   integer      NOT NULL,
    kafka_offset      bigint       NOT NULL,
    landed_at         timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_core_event_aggregate ON bronze.core_event (aggregate_type, aggregate_id);

