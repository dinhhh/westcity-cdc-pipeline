-- 5d. gold: star schema (dashboard views are in 09)

-- Date dimension (key = YYYYMMDD)
CREATE TABLE gold.dim_date (
    date_key        integer PRIMARY KEY CHECK (date_key BETWEEN 19000101 AND 29991231),
    calendar_date   date    NOT NULL UNIQUE,
    day_of_week     integer NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),   -- ISO: 1 = Monday
    week_start      date    NOT NULL,                                       -- Monday of that week
    month           integer NOT NULL CHECK (month BETWEEN 1 AND 12),
    quarter         integer NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    year            integer NOT NULL,
    is_business_day boolean NOT NULL                                        -- Monday to Friday
);

-- Customer dimension (SCD type 2)
CREATE TABLE gold.dim_customer (
    customer_key      bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- surrogate key
    customer_id       bigint       NOT NULL,                         -- business key
    customer_name     varchar(201) NOT NULL,                         -- first + last name
    residential_state varchar(3),
    marketing_consent boolean,
    valid_from        timestamptz  NOT NULL,
    valid_to          timestamptz,                                   -- NULL = current version
    is_current        boolean      NOT NULL DEFAULT true
);
-- One current row per customer
CREATE UNIQUE INDEX ux_dim_customer_current ON gold.dim_customer (customer_id) WHERE is_current;

CREATE TABLE gold.dim_product (
    product_key  integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code varchar(20)  NOT NULL UNIQUE,
    product_name varchar(100),
    product_type varchar(20)
);

CREATE TABLE gold.dim_channel (
    channel_key integer    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel     varchar(6) NOT NULL UNIQUE
);

