-- 5c. silver: Data Vault 2.0 (hubs, links, insert-only satellites)
-- hk_* = MD5 of business key, hash_diff = MD5 of attributes

-- Hubs
CREATE TABLE silver.hub_customer (
    hk_customer   char(32)     PRIMARY KEY,                          -- MD5 of customer_id
    customer_id   bigint       NOT NULL UNIQUE,                      -- business key
    load_dts      timestamptz  NOT NULL,
    record_source varchar(100) NOT NULL,
    run_id        bigint       NOT NULL
);
CREATE TABLE silver.hub_account (
    hk_account    char(32)     PRIMARY KEY,                          -- MD5 of account_id
    account_id    bigint       NOT NULL UNIQUE,
    load_dts      timestamptz  NOT NULL,
    record_source varchar(100) NOT NULL,
    run_id        bigint       NOT NULL
);
CREATE TABLE silver.hub_product (
    hk_product    char(32)     PRIMARY KEY,                          -- MD5 of product_code
    product_code  varchar(20)  NOT NULL UNIQUE,
    load_dts      timestamptz  NOT NULL,
    record_source varchar(100) NOT NULL,
    run_id        bigint       NOT NULL
);
CREATE TABLE silver.hub_device (
    hk_device          char(32)     PRIMARY KEY,                     -- MD5 of device_fingerprint
    device_fingerprint varchar(64)  NOT NULL UNIQUE,
    load_dts           timestamptz  NOT NULL,
    record_source      varchar(100) NOT NULL,
    run_id             bigint       NOT NULL
);

-- Links
CREATE TABLE silver.link_account_holder (
    hk_account_holder char(32)     PRIMARY KEY,                      -- MD5 of account_id|customer_id
    hk_account        char(32)     NOT NULL REFERENCES silver.hub_account (hk_account),
    hk_customer       char(32)     NOT NULL REFERENCES silver.hub_customer (hk_customer),
    holder_role       varchar(7)   NOT NULL,                         -- PRIMARY / JOINT
    load_dts          timestamptz  NOT NULL,
    record_source     varchar(100) NOT NULL,
    run_id            bigint       NOT NULL
);
CREATE TABLE silver.link_account_product (
    hk_account_product char(32)     PRIMARY KEY,                     -- MD5 of account_id|product_code
    hk_account         char(32)     NOT NULL REFERENCES silver.hub_account (hk_account),
    hk_product         char(32)     NOT NULL REFERENCES silver.hub_product (hk_product),
    load_dts           timestamptz  NOT NULL,
    record_source      varchar(100) NOT NULL,
    run_id             bigint       NOT NULL
);
CREATE TABLE silver.link_customer_device (
    hk_customer_device char(32)     PRIMARY KEY,                     -- MD5 of customer_id|device_fingerprint
    hk_customer        char(32)     NOT NULL REFERENCES silver.hub_customer (hk_customer),
    hk_device          char(32)     NOT NULL REFERENCES silver.hub_device (hk_device),
    load_dts           timestamptz  NOT NULL,
    record_source      varchar(100) NOT NULL,
    run_id             bigint       NOT NULL
);

