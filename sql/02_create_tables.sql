-- #############################################################################
-- 1. core_banking – system of record for customers and accounts (ER section 1)
-- #############################################################################
\connect core_banking

-- Branch: where an account is domiciled. BSB = 6-digit bank-state-branch code.
CREATE TABLE branch (
    branch_id    integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bsb          char(6)      NOT NULL UNIQUE CHECK (bsb ~ '^[0-9]{6}$'),
    branch_name  varchar(100) NOT NULL,
    state        varchar(3)   NOT NULL CHECK (state IN ('NSW','VIC','QLD','SA','WA','TAS','NT','ACT'))
);

-- Product: the account products the bank sells.
CREATE TABLE product (
    product_code  varchar(20)  PRIMARY KEY,                          -- e.g. EVERYDAY
    product_name  varchar(100) NOT NULL,
    product_type  varchar(20)  NOT NULL CHECK (product_type IN ('TRANSACTION','SAVINGS')),
    monthly_fee   numeric(8,2) NOT NULL DEFAULT 0 CHECK (monthly_fee >= 0),      -- AUD per month
    interest_rate numeric(5,2) NOT NULL DEFAULT 0 CHECK (interest_rate >= 0),    -- % per year, e.g. 4.50
    is_active     boolean      NOT NULL DEFAULT true
);

-- Customer: the customer master record.
CREATE TABLE customer (
    customer_id        bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name         varchar(100) NOT NULL,
    last_name          varchar(100) NOT NULL,
    date_of_birth      date         NOT NULL,
    email              varchar(255) NOT NULL,
    mobile             varchar(16)  NOT NULL CHECK (mobile ~ '^\+[1-9][0-9]{7,14}$'),  -- E.164, e.g. +61412345678
    marketing_consent  boolean      NOT NULL DEFAULT false,
    statement_delivery varchar(5)   NOT NULL DEFAULT 'EMAIL' CHECK (statement_delivery IN ('PAPER','EMAIL')),
    customer_since     date         NOT NULL DEFAULT current_date,
    version            integer      NOT NULL DEFAULT 1 CHECK (version >= 1),  -- aggregate version, +1 on every change
    created_at         timestamptz  NOT NULL DEFAULT now(),
    updated_at         timestamptz  NOT NULL DEFAULT now()
);

-- Customer address: history of addresses (valid_to is NULL for the current one).
CREATE TABLE customer_address (
    address_id   bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  bigint       NOT NULL REFERENCES customer (customer_id),
    address_type varchar(11)  NOT NULL CHECK (address_type IN ('RESIDENTIAL','POSTAL')),
    line1        varchar(200) NOT NULL,
    suburb       varchar(100) NOT NULL,
    state        varchar(3)   NOT NULL CHECK (state IN ('NSW','VIC','QLD','SA','WA','TAS','NT','ACT')),
    postcode     char(4)      NOT NULL CHECK (postcode ~ '^[0-9]{4}$'),
    valid_from   date         NOT NULL DEFAULT current_date,
    valid_to     date,                                               -- NULL = current address
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);
-- At most one CURRENT address of each type per customer.
CREATE UNIQUE INDEX ux_customer_address_current
    ON customer_address (customer_id, address_type) WHERE valid_to IS NULL;

-- Account: a customer's bank account. Opened as PENDING until the fraud
-- decision makes it ACTIVE or REJECTED.
CREATE TABLE account (
    account_id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id             integer     NOT NULL REFERENCES branch (branch_id),
    account_number        varchar(9)  NOT NULL CHECK (account_number ~ '^[0-9]{6,9}$'),
    product_code          varchar(20) NOT NULL REFERENCES product (product_code),
    account_status        varchar(8)  NOT NULL DEFAULT 'PENDING'
                          CHECK (account_status IN ('PENDING','ACTIVE','REJECTED','CLOSED')),
    channel               varchar(6)  NOT NULL CHECK (channel IN ('MOBILE','BRANCH','WEB')),
    opened_at             timestamptz NOT NULL DEFAULT now(),
    activated_at          timestamptz CHECK (activated_at >= opened_at),
    closed_at             timestamptz CHECK (closed_at >= opened_at),
    onboarding_session_id uuid,                                      -- logical key -> identity_fraud.onboarding_session
    version               integer     NOT NULL DEFAULT 1 CHECK (version >= 1),  -- aggregate version
    updated_at            timestamptz NOT NULL DEFAULT now(),        -- last change (set by the version trigger in 03)
    UNIQUE (branch_id, account_number)                               -- account number is unique within a branch (BSB)
);

-- Account holder: which customers own which accounts (many-to-many).
CREATE TABLE account_holder (
    account_id  bigint      NOT NULL REFERENCES account (account_id),
    customer_id bigint      NOT NULL REFERENCES customer (customer_id),
    holder_role varchar(7)  NOT NULL CHECK (holder_role IN ('PRIMARY','JOINT')),
    added_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (account_id, customer_id)
);
-- Exactly one PRIMARY holder per account (JOINT holders are unlimited).
CREATE UNIQUE INDEX ux_account_holder_primary
    ON account_holder (account_id) WHERE holder_role = 'PRIMARY';
CREATE INDEX ix_account_holder_customer ON account_holder (customer_id);

-- Outbox: business events written in the SAME transaction as the change,
-- then read by Debezium and published to Kafka (transactional outbox pattern).
-- Column names follow Debezium's outbox event router defaults.
CREATE TABLE outbox (
    id            uuid         PRIMARY KEY DEFAULT gen_random_uuid(),  -- event id
    aggregatetype varchar(255) NOT NULL CHECK (aggregatetype IN ('account','customer')),  -- picks the Kafka topic
    aggregateid   varchar(255) NOT NULL,                              -- account_id or customer_id = Kafka key
    type          varchar(255) NOT NULL CHECK (type IN ('CustomerCreated','CustomerDetailsUpdated',
                                                        'AccountOpened','AccountActivated',
                                                        'AccountRejected','AccountSnapshot')),
    event_version integer      NOT NULL,                              -- aggregate version after the change
    payload       jsonb        NOT NULL,                              -- full event, see docs/event-contract.md
    tx_id         bigint       NOT NULL DEFAULT txid_current(),       -- source transaction id, for lineage
    created_at    timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_outbox_created_at ON outbox (created_at);


-- #############################################################################
-- 2. identity_fraud – identity verification and fraud platform (ER section 2)
--    Kept to the columns the dashboards use (docs/demo-flow.md 2.1, 5 and 6)
--    plus keys. The scoring rules are in sql/05_fraud_scoring.sql.
-- #############################################################################
\connect identity_fraud

-- Device: a phone/computer used to sign up, identified by a hashed
-- fingerprint. Several customers on ONE device is a fraud-ring signal.
CREATE TABLE device (
    device_id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_fingerprint varchar(64) NOT NULL UNIQUE                   -- hash, never the raw device id
);

-- Onboarding session: one sign-up journey by one customer on one device.
-- core_banking.account.onboarding_session_id points here (logical key).
CREATE TABLE onboarding_session (
    session_id  uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id bigint      NOT NULL,                                -- logical key -> core_banking.customer
    device_id   bigint      NOT NULL REFERENCES device (device_id),
    started_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_onboarding_session_device ON onboarding_session (device_id);  -- "customers sharing a device"

-- KYC verification: result of each identity check. A customer referred on
-- the first attempt may try again (attempt_no = 2); the LATEST attempt counts.
CREATE TABLE kyc_verification (
    kyc_id      bigint     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint     NOT NULL,                                 -- logical key -> core_banking.customer
    attempt_no  integer    NOT NULL DEFAULT 1 CHECK (attempt_no >= 1),
    result      varchar(5) NOT NULL CHECK (result IN ('PASS','FAIL','REFER')),
    UNIQUE (customer_id, attempt_no)
);

-- Watchlist screening: sanctions / politically exposed person check,
-- one per customer in the prototype.
CREATE TABLE watchlist_screening (
    screening_id bigint     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  bigint     NOT NULL UNIQUE,                         -- logical key -> core_banking.customer
    match_status varchar(9) NOT NULL CHECK (match_status IN ('CLEAR','POSSIBLE','CONFIRMED'))
);

-- Risk assessment: the fraud engine's score, band and decision for one new
-- account (rules in sql/05_fraud_scoring.sql). One assessment per account.
CREATE TABLE risk_assessment (
    assessment_id bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    bigint      NOT NULL UNIQUE,                       -- logical key -> core_banking.account
    customer_id   bigint      NOT NULL,                              -- logical key -> core_banking.customer
    risk_score    integer     NOT NULL CHECK (risk_score BETWEEN 0 AND 100),
    risk_band     varchar(6)  NOT NULL CHECK (risk_band IN ('LOW','MEDIUM','HIGH')),
    decision      varchar(7)  NOT NULL CHECK (decision IN ('APPROVE','REVIEW','DECLINE')),
    reason_codes  text,                                              -- e.g. 'SHARED_DEVICE,KYC_FAIL' (NULL = no signals)
    assessed_at   timestamptz NOT NULL DEFAULT now()                 -- decision time
);

-- Processed event: ids of Kafka events already handled (makes the consumer idempotent).
CREATE TABLE processed_event (
    event_id     uuid        PRIMARY KEY,
    processed_at timestamptz NOT NULL DEFAULT now()
);


-- #############################################################################
-- 3. crm – customer relationship management (ER section 3)
--    Kept to the columns the dashboards use (docs/demo-flow.md 2.3, 5 and 6)
--    plus the keys and sync columns the pipeline needs. The rules that fill
--    them are in sql/04_crm_onboarding.sql.
-- #############################################################################
\connect crm

-- CRM contact: one row per customer.
-- segment = customer group by age when the account was opened.
CREATE TABLE crm_contact (
    contact_id     bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    bigint      NOT NULL UNIQUE,                      -- golden key from core_banking
    segment        varchar(18) NOT NULL
                   CHECK (segment IN ('STUDENT','YOUNG_PROFESSIONAL','FAMILY','SENIOR')),
    source_version integer     NOT NULL,                             -- core customer.version last applied
    synced_at      timestamptz NOT NULL DEFAULT now()
);

-- CRM financial account: one row per account, with where the customer is in
-- their journey. lifecycle_stage is kept HERE rather than on crm_contact
-- because it follows the ACCOUNT status, so it must be guarded by the
-- account version (a customer event does not change it).
CREATE TABLE crm_financial_account (
    fin_account_id  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      bigint      NOT NULL UNIQUE,                     -- golden key from core_banking
    contact_id      bigint      NOT NULL REFERENCES crm_contact (contact_id),
    account_status  varchar(8)  NOT NULL
                    CHECK (account_status IN ('PENDING','ACTIVE','REJECTED','CLOSED')),
    lifecycle_stage varchar(14) NOT NULL
                    CHECK (lifecycle_stage IN ('UNDER_REVIEW','NEW_ONBOARDING','ESTABLISHED','DECLINED')),
    source_version  integer     NOT NULL,                            -- core account.version last applied
    synced_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_crm_financial_account_contact ON crm_financial_account (contact_id);

-- CRM case: tasks owned by CRM. The prototype creates one WELCOME_CALL task
-- per approved (ACTIVE) account.
CREATE TABLE crm_case (
    case_id     bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  bigint      NOT NULL REFERENCES crm_financial_account (account_id),
    case_type   varchar(12) NOT NULL DEFAULT 'WELCOME_CALL' CHECK (case_type IN ('WELCOME_CALL')),
    case_status varchar(9)  NOT NULL DEFAULT 'OPEN' CHECK (case_status IN ('OPEN','COMPLETED')),
    opened_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (account_id, case_type)                                   -- at most one welcome call per account
);

-- Processed event: ids of Kafka events already handled (idempotent consumer).
CREATE TABLE processed_event (
    event_id     uuid        PRIMARY KEY,
    processed_at timestamptz NOT NULL DEFAULT now()
);


-- #############################################################################
-- 4. loyalty – rewards and loyalty platform (ER section 4)
--    Kept to the columns the dashboards use (docs/demo-flow.md 2.4, 5 and 6)
--    plus keys and sync columns. The rules are in sql/06_loyalty_onboarding.sql.
-- #############################################################################
\connect loyalty

-- Loyalty offer: the welcome offers (reference data, loaded by
-- sql/07_reference_data.sql): EVERYDAY 5,000 points, SAVINGS 3,000,
-- and one row with product_code NULL = any other product, 1,000 points.
CREATE TABLE loyalty_offer (
    offer_id     integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code varchar(20) UNIQUE,                                 -- logical key -> core_banking.product
    bonus_points integer     NOT NULL CHECK (bonus_points > 0)
);

-- Loyalty member: one per enrolled customer. Customers are only ever enrolled
-- with an ACTIVE account and marketing consent; declined customers never
-- become members. UNENROLLED = removed after an account was rejected.
CREATE TABLE loyalty_member (
    member_id     bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   bigint      NOT NULL UNIQUE,                       -- golden key from core_banking
    member_status varchar(10) NOT NULL DEFAULT 'ENROLLED'
                  CHECK (member_status IN ('ENROLLED','UNENROLLED')),
    tier          varchar(6)  NOT NULL DEFAULT 'BRONZE'
                  CHECK (tier IN ('BRONZE','SILVER','GOLD')),        -- all new members start at BRONZE
    synced_at     timestamptz NOT NULL DEFAULT now()
);

-- Member offer: the welcome offer given for ONE enrolled account.
CREATE TABLE member_offer (
    account_id        bigint      PRIMARY KEY,                       -- golden key from core_banking: one offer per account
    member_id         bigint      NOT NULL REFERENCES loyalty_member (member_id),
    offer_id          integer     NOT NULL REFERENCES loyalty_offer (offer_id),
    assigned_at       timestamptz NOT NULL DEFAULT now(),
    redemption_status varchar(8)  NOT NULL DEFAULT 'ASSIGNED'
                      CHECK (redemption_status IN ('ASSIGNED','REDEEMED')),
    source_version    integer     NOT NULL,                          -- core account.version last applied
    synced_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_member_offer_member ON member_offer (member_id);

-- Processed event: ids of Kafka events already handled (idempotent consumer).
CREATE TABLE processed_event (
    event_id     uuid        PRIMARY KEY,
    processed_at timestamptz NOT NULL DEFAULT now()
);


-- #############################################################################
-- 5. westcity_dw – integrated data warehouse (ER sections 5, 6 and 7),
--    built in MEDALLION layers, one schema each:
--      bronze  raw source data exactly as it arrived:
--                * core_banking events, landed from Kafka by consumer-dw
--                * rows extracted from identity_fraud, crm and loyalty by
--                  etl/01_extract_bronze.sql (postgres_fdw + watermarks)
--      silver  Data Vault 2.0 (the ER model's raw_vault): hubs, links and
--              insert-only satellites, loaded by etl/02_load_silver.sql
--      gold    star schema (the ER model's mart), loaded by
--              etl/03_load_gold.sql, plus the dashboard views (sql/09)
--      ops     audit: ETL runs, data-quality quarantine, extract watermarks
--    Tables keep only the columns the dashboards need (docs/demo-flow.md
--    sections 5 and 6), plus keys and lineage columns.
-- #############################################################################
\connect westcity_dw

CREATE SCHEMA bronze;
CREATE SCHEMA silver;
CREATE SCHEMA gold;
CREATE SCHEMA ops;

-- =============================================================================
-- 5a. ops – audit and data quality (ER section 7)
--     Created first because every other layer records which run loaded it.
-- =============================================================================

-- ETL run: one row per run of an etl/ script; its run_id is stamped on every
-- row that run writes (lineage, UC5).
CREATE TABLE ops.etl_run (
    run_id         bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_name       varchar(100) NOT NULL,                            -- e.g. '01_extract_bronze'
    script_version varchar(40)  NOT NULL,                            -- hard-coded in the script, e.g. 'v1'
    started_at     timestamptz  NOT NULL DEFAULT now(),
    finished_at    timestamptz,
    status         varchar(9)   NOT NULL DEFAULT 'RUNNING' CHECK (status IN ('RUNNING','SUCCEEDED','FAILED')),
    rows_read      integer      NOT NULL DEFAULT 0,
    rows_loaded    integer      NOT NULL DEFAULT 0,
    rows_rejected  integer      NOT NULL DEFAULT 0
);

-- DQ quarantine: rows that failed a data-quality rule. They are kept here,
-- with the reason, instead of being loaded into silver.
CREATE TABLE ops.dq_quarantine (
    quarantine_id  bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         bigint       NOT NULL REFERENCES ops.etl_run (run_id),
    source_table   varchar(100) NOT NULL,
    record_key     varchar(100) NOT NULL,
    rule_name      varchar(100) NOT NULL,
    reason         text         NOT NULL,
    raw_record     jsonb,                                            -- the rejected row as it arrived
    quarantined_at timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (source_table, record_key, rule_name)                     -- report each problem once
);

-- Extract watermark: how far etl/01_extract_bronze.sql has read each source
-- table, so the next run only copies NEW or CHANGED rows (incremental).
-- A table uses an id that only grows (insert-only tables) or its synced_at
-- time (tables whose rows are updated). Rows are added by sql/08.
CREATE TABLE ops.extract_watermark (
    source_table     varchar(60) PRIMARY KEY,                        -- e.g. 'crm.crm_case'
    watermark_column varchar(30) NOT NULL,                           -- the source column compared
    last_id          bigint,                                         -- highest id copied so far
    last_ts          timestamptz,                                    -- latest synced_at copied so far
    run_id           bigint,                                         -- run that last moved it
    updated_at       timestamptz NOT NULL DEFAULT now()
);

-- =============================================================================
-- 5b. bronze – raw data as it arrived, plus where and when it came from.
--     No business rules and no constraints besides keys: bronze must accept
--     whatever the sources send, so nothing is lost before silver checks it.
--     Extracted tables are named <source system>_<table>.
-- =============================================================================

-- Core banking events, landed from Kafka by consumer-dw through
-- bronze.land_core_event() (sql/08). Every event carries the full account
-- or customer snapshot, so core_banking needs no table extract.
CREATE TABLE bronze.core_event (
    event_id          uuid         PRIMARY KEY,                      -- = outbox id: a repeat delivery is ignored
    event_type        varchar(40)  NOT NULL,                         -- e.g. AccountOpened
    aggregate_type    varchar(20)  NOT NULL,                         -- 'customer' or 'account'
    aggregate_id      bigint       NOT NULL,                         -- customer_id or account_id
    aggregate_version integer      NOT NULL,                         -- version after the change
    occurred_at       timestamptz  NOT NULL,                         -- commit time in core_banking
    payload           jsonb        NOT NULL,                         -- the whole event, unchanged
    kafka_topic       varchar(100) NOT NULL,                         -- lineage: where it was read in Kafka
    kafka_partition   integer      NOT NULL,
    kafka_offset      bigint       NOT NULL,
    landed_at         timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_core_event_aggregate ON bronze.core_event (aggregate_type, aggregate_id);

-- Extracted tables: the source columns + run_id (which extract run copied
-- the row) + loaded_at. Incremental tables are an append log: a changed
-- source row is copied again, and silver takes the latest copy.
CREATE TABLE bronze.core_product (                                -- full copy each run (reference data)
    product_code varchar(20), product_name varchar(100), product_type varchar(20),
    run_id bigint NOT NULL, loaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE bronze.fraud_device (                                -- watermark: device_id
    device_id bigint, device_fingerprint varchar(64),
    run_id bigint NOT NULL, loaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE bronze.fraud_onboarding_session (                    -- full copy each run (no usable watermark)
    session_id uuid, customer_id bigint, device_id bigint, started_at timestamptz,
    run_id bigint NOT NULL, loaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE bronze.fraud_kyc_verification (                      -- watermark: kyc_id
    kyc_id bigint, customer_id bigint, attempt_no integer, result varchar(5),
    run_id bigint NOT NULL, loaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE bronze.fraud_watchlist_screening (                   -- watermark: screening_id
    screening_id bigint, customer_id bigint, match_status varchar(9),
    run_id bigint NOT NULL, loaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE bronze.fraud_risk_assessment (                       -- watermark: assessment_id
    assessment_id bigint, account_id bigint, customer_id bigint, risk_score integer,
    risk_band varchar(6), decision varchar(7), reason_codes text, assessed_at timestamptz,
    run_id bigint NOT NULL, loaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE bronze.crm_contact (                                 -- watermark: synced_at
    contact_id bigint, customer_id bigint, segment varchar(18), source_version integer,
    synced_at timestamptz,
    run_id bigint NOT NULL, loaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE bronze.crm_financial_account (                       -- watermark: synced_at
    fin_account_id bigint, account_id bigint, contact_id bigint, account_status varchar(8),
    lifecycle_stage varchar(14), source_version integer, synced_at timestamptz,
    run_id bigint NOT NULL, loaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE bronze.crm_case (                                    -- watermark: case_id
    case_id bigint, account_id bigint, case_type varchar(12), case_status varchar(9),
    opened_at timestamptz,
    run_id bigint NOT NULL, loaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE bronze.loyalty_offer (                               -- full copy each run (reference data)
    offer_id integer, product_code varchar(20), bonus_points integer,
    run_id bigint NOT NULL, loaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE bronze.loyalty_member (                              -- watermark: synced_at
    member_id bigint, customer_id bigint, member_status varchar(10), tier varchar(6),
    synced_at timestamptz,
    run_id bigint NOT NULL, loaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE bronze.loyalty_member_offer (                        -- watermark: synced_at
    account_id bigint, member_id bigint, offer_id integer, assigned_at timestamptz,
    redemption_status varchar(8), source_version integer, synced_at timestamptz,
    run_id bigint NOT NULL, loaded_at timestamptz NOT NULL DEFAULT now()
);

-- =============================================================================
-- 5c. silver – Data Vault 2.0 (ER section 5)
--     Hubs  = one row per business key, ever (customer, account, ...).
--     Links = one row per relationship between business keys.
--     Satellites = descriptive attributes with FULL HISTORY: INSERT-ONLY, a
--     new row is added (with a new load_dts) only when the attributes change.
--     Hash keys (hk_*) = MD5 of the business key; hash_diff = MD5 of all the
--     satellite's attributes, used to spot a change in one comparison.
--     run_id is a logical reference to ops.etl_run.
-- =============================================================================

-- Hubs.
CREATE TABLE silver.hub_customer (
    hk_customer   char(32)     PRIMARY KEY,                          -- MD5 of customer_id
    customer_id   bigint       NOT NULL UNIQUE,                      -- business key
    load_dts      timestamptz  NOT NULL,
    record_source varchar(100) NOT NULL,
    run_id        bigint       NOT NULL
);
CREATE TABLE silver.hub_account (
    hk_account    char(32)     PRIMARY KEY,                          -- MD5 of account_id
    account_id    bigint       NOT NULL UNIQUE,
    load_dts      timestamptz  NOT NULL,
    record_source varchar(100) NOT NULL,
    run_id        bigint       NOT NULL
);
CREATE TABLE silver.hub_product (
    hk_product    char(32)     PRIMARY KEY,                          -- MD5 of product_code
    product_code  varchar(20)  NOT NULL UNIQUE,
    load_dts      timestamptz  NOT NULL,
    record_source varchar(100) NOT NULL,
    run_id        bigint       NOT NULL
);
CREATE TABLE silver.hub_device (
    hk_device          char(32)     PRIMARY KEY,                     -- MD5 of device_fingerprint
    device_fingerprint varchar(64)  NOT NULL UNIQUE,
    load_dts           timestamptz  NOT NULL,
    record_source      varchar(100) NOT NULL,
    run_id             bigint       NOT NULL
);

-- Links.
CREATE TABLE silver.link_account_holder (
    hk_account_holder char(32)     PRIMARY KEY,                      -- MD5 of account_id|customer_id
    hk_account        char(32)     NOT NULL REFERENCES silver.hub_account (hk_account),
    hk_customer       char(32)     NOT NULL REFERENCES silver.hub_customer (hk_customer),
    holder_role       varchar(7)   NOT NULL,                         -- PRIMARY / JOINT
    load_dts          timestamptz  NOT NULL,
    record_source     varchar(100) NOT NULL,
    run_id            bigint       NOT NULL
);
CREATE TABLE silver.link_account_product (
    hk_account_product char(32)     PRIMARY KEY,                     -- MD5 of account_id|product_code
    hk_account         char(32)     NOT NULL REFERENCES silver.hub_account (hk_account),
    hk_product         char(32)     NOT NULL REFERENCES silver.hub_product (hk_product),
    load_dts           timestamptz  NOT NULL,
    record_source      varchar(100) NOT NULL,
    run_id             bigint       NOT NULL
);
CREATE TABLE silver.link_customer_device (
    hk_customer_device char(32)     PRIMARY KEY,                     -- MD5 of customer_id|device_fingerprint
    hk_customer        char(32)     NOT NULL REFERENCES silver.hub_customer (hk_customer),
    hk_device          char(32)     NOT NULL REFERENCES silver.hub_device (hk_device),
    load_dts           timestamptz  NOT NULL,
    record_source      varchar(100) NOT NULL,
    run_id             bigint       NOT NULL
);

-- Satellites. Primary key = (hub key, load_dts): one version per load.
-- From core_banking (Kafka events):
CREATE TABLE silver.sat_customer_details (
    hk_customer       char(32)     NOT NULL REFERENCES silver.hub_customer (hk_customer),
    load_dts          timestamptz  NOT NULL,
    hash_diff         char(32)     NOT NULL,
    first_name        varchar(100),
    last_name         varchar(100),
    date_of_birth     date,
