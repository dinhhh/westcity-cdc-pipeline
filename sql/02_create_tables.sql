-- Date dimension: one row per calendar day, key = YYYYMMDD (e.g. 20261005).
-- Filled by etl/03_load_gold.sql for the days the facts need.
CREATE TABLE gold.dim_date (
    date_key        integer PRIMARY KEY CHECK (date_key BETWEEN 19000101 AND 29991231),
    calendar_date   date    NOT NULL UNIQUE,
    day_of_week     integer NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),   -- ISO: 1 = Monday
    week_start      date    NOT NULL,                                       -- Monday of that week
    month           integer NOT NULL CHECK (month BETWEEN 1 AND 12),
    quarter         integer NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    year            integer NOT NULL,
    is_business_day boolean NOT NULL                                        -- Monday to Friday
);

-- Customer dimension, SCD type 2: when a customer's details change, the
-- current row is closed (valid_to, is_current = false) and a new one added.
CREATE TABLE gold.dim_customer (
    customer_key      bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- surrogate key
    customer_id       bigint       NOT NULL,                         -- business key
    customer_name     varchar(201) NOT NULL,                         -- first + last name
    residential_state varchar(3),
    marketing_consent boolean,
    valid_from        timestamptz  NOT NULL,
    valid_to          timestamptz,                                   -- NULL = current version
    is_current        boolean      NOT NULL DEFAULT true
);
-- Only one current row per customer.
CREATE UNIQUE INDEX ux_dim_customer_current ON gold.dim_customer (customer_id) WHERE is_current;

CREATE TABLE gold.dim_product (
    product_key  integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code varchar(20)  NOT NULL UNIQUE,
    product_name varchar(100),
    product_type varchar(20)
);

CREATE TABLE gold.dim_channel (
    channel_key integer    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel     varchar(6) NOT NULL UNIQUE
);

-- Fact: ONE combined row per account opening, with what every system added
-- (docs/demo-flow.md section 5). Grain = account.
CREATE TABLE gold.fact_account_opening (
    account_id              bigint       PRIMARY KEY,                -- degenerate dimension
    open_date_key           integer      NOT NULL REFERENCES gold.dim_date (date_key),
    customer_key            bigint       NOT NULL REFERENCES gold.dim_customer (customer_key),  -- PRIMARY holder
    product_key             integer      NOT NULL REFERENCES gold.dim_product (product_key),
    channel_key             integer      NOT NULL REFERENCES gold.dim_channel (channel_key),
    -- core banking
    opened_at               timestamptz  NOT NULL,
    activated_at            timestamptz,
    account_status          varchar(8)   NOT NULL,
    age_band                varchar(5)   NOT NULL,                   -- age at opening, e.g. '25-34'
    -- identity & fraud
    kyc_result              varchar(5),                              -- latest attempt
    kyc_attempts            integer,
    risk_score              integer,
    risk_band               varchar(6),
    risk_decision           varchar(7),                              -- NULL = not scored yet
    reason_codes            text,
    minutes_to_decision     numeric(10,2),                           -- assessed_at - opened_at
    device_fingerprint      varchar(64),                             -- device used to sign up
    shared_device_customers integer,                                 -- customers on that device (incl. this one)
    -- crm
    segment                 varchar(18),
    lifecycle_stage         varchar(14),
    crm_account_status      varchar(8),                              -- NULL = CRM has no record
    welcome_task_created    boolean      NOT NULL,
    welcome_task_status     varchar(9),
    -- loyalty
    loyalty_enrolled        boolean      NOT NULL,
    tier                    varchar(6),
    welcome_offer_points    integer,
    offer_redeemed          boolean      NOT NULL,
    -- derived
    is_approved             boolean      NOT NULL,                   -- account ACTIVE
    is_declined             boolean      NOT NULL,                   -- account REJECTED
    opening_count           integer      NOT NULL DEFAULT 1 CHECK (opening_count = 1),  -- for SUM() in reports
    run_id                  bigint       NOT NULL                    -- the gold load that built this row
);
